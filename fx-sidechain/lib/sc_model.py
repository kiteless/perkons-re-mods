"""fx-sidechain: the value of each step on the four rows (shared by the patch and tests)."""
SR = 48000

# The rows are aimed at live performance: pumping and chopping, not subtle mixing.
# row 1: how deep the duck goes, in dB (step 16: silent)
DEPTH_DB = [3, 4.5, 6, 7.5, 9, 10.5, 12, 13.5, 15, 16.5, 18, 21, 24, 30, 40, None]
# row 2: attack, ms
ATTACK_MS = [0.5, 1, 1.5, 2, 3, 4, 5, 6, 8, 10, 13, 16, 20, 25, 35, 50]
# row 3: hold, ms (step 1: none; 25 ms steps through 100-300, where pumping happens)
HOLD_MS = [0, 10, 25, 50, 75, 100, 125, 150, 175, 200, 225, 250, 275, 300, 400, 500]
# row 4: release, ms: the time until the voices are back to normal (the duck down to BACK
# of its depth: within ~1 dB of the full level at any depth); the release itself runs on
# to FLOOR (about 2.1 times as long)
RELEASE_MS = [10, 25, 50, 75, 100, 125, 150, 190, 250, 300, 375, 440, 500, 625, 750, 1000]
BACK = 0.11
FLOOR = 0.01

# the build's default settings (step indexes 0-15): voice 1 ducks the others 15 dB, 1 ms
# attack, 150 ms hold, back after 300 ms (a classic pump at 120-130 BPM)
DEFAULTS = {'master': 0, 'depth': 8, 'attack': 1, 'hold': 7, 'release': 9}


def depth(i):
    """Row 1 step i: the duck's depth as a fraction of the level (gain = 1 - depth * x)."""
    db = DEPTH_DB[i]
    return 1.0 if db is None else 1.0 - 10 ** (-db / 20)


def attack_inc(i):
    return 1.0 / max(1.0, ATTACK_MS[i] * SR / 1000)


def hold_samples(i):
    return round(HOLD_MS[i] * SR / 1000)


def release_k(i):
    return BACK ** (1.0 / (RELEASE_MS[i] * SR / 1000))


def tables_header():
    def row(vals, fmt):
        return ', '.join(fmt(v) for v in vals)
    f = lambda v: f'{float(v):.9e}f'  # noqa: E731
    return ('/* generated by fx-sidechain/lib/sc_model.py -- do not edit */\n#pragma once\n#include <stdint.h>\n'
            f'static const float PK_SC_DEPTH[16] = {{{row(map(depth, range(16)), f)}}};\n'
            f'static const float PK_SC_ATTACK[16] = {{{row(map(attack_inc, range(16)), f)}}};\n'
            f'static const uint32_t PK_SC_HOLD[16] = {{{row(map(hold_samples, range(16)), str)}}};\n'
            f'static const float PK_SC_RELEASE[16] = {{{row(map(release_k, range(16)), f)}}};\n')
