"""voice-step-sampler: STEP SAMPLER, a voice-map engine playing up to 64 samples per bank,
of any length, streamed from the SD card, each step its own sample (M7 + M4), on the
platform's voice map. It takes over the RAM of the stock custom samples: stock
ALGO 3 plays its factory samples while it's installed."""
import os

from perkons import m4host
from perkons.patch import PatchError

TARGET = 'v1.3.0'
SUMMARY = 'STEP SAMPLER for voice-map: 64 streamed samples per bank, a sample per step'

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_M7 = os.path.join(MOD, 'src', 'm7')
SRC_M4 = os.path.join(MOD, 'src', 'm4')
SRC_COMMON = os.path.join(MOD, 'src', 'common')
NAME = 'step_sampler'


def apply(p, arg=None):
    """arg: the voice slot (engine number, 5-16) it's installed in; none: the next free one."""
    vm = p.shared.setdefault('voice_map', {'engines': {}})
    if NAME in vm['engines']:
        raise PatchError(f'voice-map engine name {NAME} already taken')
    vm['engines'][NAME] = {'sources': [os.path.join(SRC_M7, 'step_sampler.c')],
                           'include_dirs': [SRC_M7, SRC_COMMON], 'build': 'pk_ss_build',
                           'slot': int(arg) if arg else None}

    def engine_header():
        if not p.shared['voice_map'].get('m7'):
            raise PatchError('voice-step-sampler is a voice-map engine: build it together with voice_map')
        from perkons.voicemap import numbered
        slot = next(k for k, (n, _) in numbered(p).items() if n == NAME)
        return ('/* generated by voice-step-sampler/patches/voice_step_sampler.py -- do not edit */\n'
                f'#pragma once\n#define PK_SS_ENGINE {slot - 1}     /* voice-map engine {slot}: the nibble value */\n')

    h = m4host.host(p)
    h.add([os.path.join(SRC_M4, 'ss_m4.c'), os.path.join(SRC_M4, 'ss_page.c')], [SRC_M4, SRC_COMMON],
          init='pk_ss_init', headers={'pk_ss_engine.h': engine_header})
    h.page('samples', key='pk_ss_page_key', draw='pk_ss_page_draw', leave='pk_ss_page_leave')
    h.replace_word('keys.handler_lit', 'pk_ss_key_event', 'step + SHUFFLE: the sample page; CLEAR / copy / paste: step samples')
    for site in ('boot_init.call_load_samples', 'switch_bank.call_load_samples',
                 'boot_load_last_bank.call_load_samples'):
        h.redirect_call(site, 'pk_ss_load_samples', 'bank load: STEP SAMPLER\'s 64 samples (stock\'s three: factory)')
    h.redirect_call('send_triggers.call_ipc_send', 'pk_ss_triggers', 'triggers: what each STEP SAMPLER hit plays')
    for site in ('seq_tick.tail_send_triggers', 'send_triggers_thunk.tail'):
        h.redirect_branch(site, 'pk_ss_send', 'send_triggers: the sequencer\'s fired flags')
    h.redirect_call('main.call_key_poll', 'pk_ss_poll', 'main loop: STEP SAMPLER streams and prepared starts')
    h.store('kit', 'SSKT', 'pk_ss_kit_save', 'pk_ss_kit_restore')
    h.store('pattern', 'SSPT', 'pk_ss_pat_save', 'pk_ss_pat_restore')
    p.ram_takeover('store', 'default custom samples', 'voice-step-sampler')
    p.ram_borrow('store', 'json_buf', 'voice-step-sampler')     # card reads bounce through it

    def needs_voice_map():
        if not p.shared['voice_map'].get('m7'):
            raise PatchError('voice-step-sampler is a voice-map engine: build it together with voice_map')
    p.on_finish(needs_voice_map)
